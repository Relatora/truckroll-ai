using System.Globalization;
using System.Text;
using System.Text.Json;
using Truckroll.Api.Features.Dispatch.Suggestions;
using Truckroll.Data.Domain;

namespace Truckroll.Eval;

/// <summary>
/// The dispatch eval: scenarios a dispatcher has an answer for, run through the same
/// <see cref="DispatchScorer"/> the API uses. Offline: no stack, no model, no database.
/// </summary>
internal static class DispatchEval
{
    /// <summary>The bar from issue #14: the expected technician in the top three this often.</summary>
    public const double TopThreeBar = 0.90;

    private static readonly GeoPoint Branch = new(43.55, -80.25);
    private static readonly DateOnly Day = new(2026, 12, 1);
    private static readonly TimeSpan Ontario = TimeSpan.FromHours(-5);

    public sealed record Result(Scenario Scenario, int? Rank, IReadOnlyList<ScoredTechnician> Ranked, IReadOnlyList<RuledOut> RuledOut);

    public static async Task<List<string>> RunAsync(string root, bool write)
    {
        var file = JsonSerializer.Deserialize<ScenarioFile>(await File.ReadAllTextAsync(Path.Combine(root, "evals", "dispatch.json")), Json)
            ?? throw new InvalidOperationException("evals/dispatch.json is empty.");

        var results = file.Scenarios.Select(Run).ToList();
        foreach (var result in results)
        {
            Console.WriteLine($"{(result.Rank is { } r ? $"#{r}" : "miss"),5}  {result.Scenario.Id}  (top: {string.Join(", ", result.Ranked.Take(3).Select(t => t.Name))})");
        }

        var top1 = results.Count(r => r.Rank == 1) / (double)results.Count;
        var top3 = results.Count(r => r.Rank <= 3) / (double)results.Count;
        Console.WriteLine(string.Create(CultureInfo.InvariantCulture, $"\ndispatch   top-1 {top1:0.00}  top-3 {top3:0.00}  ({results.Count} scenarios)"));

        if (write)
        {
            var path = Path.Combine(root, "evals", "dispatch-results.md");
            await File.WriteAllTextAsync(path, Markdown(results, top1, top3));
            Console.WriteLine($"Wrote {Path.GetRelativePath(Environment.CurrentDirectory, path)}");
        }

        return top3 >= TopThreeBar ? [] : [string.Create(CultureInfo.InvariantCulture, $"dispatch top-3 is {top3:0.00}, below {TopThreeBar:0.00}")];
    }

    private static Result Run(Scenario scenario)
    {
        var job = new DispatchJob(
            Enum.Parse<TechnicianSkills>(scenario.Job.Work),
            Enum.Parse<Certifications>(scenario.Job.Licence),
            Time(scenario.Job.Window, start: true),
            Time(scenario.Job.Window, start: false),
            scenario.Job.Minutes,
            Point(scenario.Job.At));

        var visitNumber = 0;
        var candidates = scenario.Technicians.Select((t, i) => new Candidate(
            i + 1,
            t.Name,
            Enum.Parse<TechnicianSkills>(t.Skills),
            Enum.Parse<Certifications>(t.Licences),
            Branch,
            "home",
            (t.Day ?? []).Select(v => new Visit(
                $"J-{++visitNumber}", Time(v.Window, start: true), Time(v.Window, start: false), v.Minutes, Point(v.At), $"job {visitNumber}")).ToList()));

        var ranking = DispatchScorer.Rank(job, candidates);
        var index = ranking.Ranked.ToList().FindIndex(t => t.Name == scenario.Expect);
        return new Result(scenario, index < 0 ? null : index + 1, ranking.Ranked, ranking.RuledOut);
    }

    private static string Markdown(List<Result> results, double top1, double top3)
    {
        var page = new StringBuilder();
        void Line(string text = "") => page.Append(text).Append('\n');

        Line("# Dispatch eval results");
        Line();
        Line("<!-- Generated by `dotnet run --project tools/Truckroll.Eval -- --suite dispatch --write`. Don't edit by hand: change evals/dispatch.json or the scorer, and run it again. -->");
        Line();
        Line(string.Create(CultureInfo.InvariantCulture, $"{results.Count} scenarios from [dispatch.json](dispatch.json), each with the technician an experienced dispatcher would send, run through `DispatchScorer` (the same code the API ranks with). The scenarios were written before the scorer was run on them."));
        Line();
        Line(top3 >= TopThreeBar
            ? string.Create(CultureInfo.InvariantCulture, $"**Bar met:** the expected technician is in the top three in {top3 * 100:0}% of scenarios (the bar is {TopThreeBar * 100:0}%), and first in {top1 * 100:0}%.")
            : string.Create(CultureInfo.InvariantCulture, $"**Bar missed:** the expected technician is in the top three in {top3 * 100:0}% of scenarios; the bar is {TopThreeBar * 100:0}%."));
        Line();
        Line("| Scenario | Expected | Rank | Ranked top three | Ruled out |");
        Line("| -------- | -------- | ---: | ---------------- | --------- |");
        foreach (var r in results)
        {
            var top = string.Join(", ", r.Ranked.Take(3).Select(t => string.Create(CultureInfo.InvariantCulture, $"{t.Name} ({t.Score:0.00})")));
            var outs = r.RuledOut.Count == 0 ? "" : string.Join("; ", r.RuledOut.Select(o => $"{o.Name}: {o.Reason}"));
            Line($"| {r.Scenario.Id} | {r.Scenario.Expect} | {(r.Rank is { } rank ? rank.ToString(CultureInfo.InvariantCulture) : "–")} | {top} | {outs} |");
        }

        Line();
        Line("## Why each answer is the right one");
        Line();
        foreach (var r in results)
        {
            Line($"- **{r.Scenario.Id}:** {r.Scenario.Why}");
        }

        return page.ToString();
    }

    private static DateTimeOffset Time(string window, bool start)
    {
        var part = window.Split('-')[start ? 0 : 1];
        var time = TimeOnly.ParseExact(part, "HH:mm", CultureInfo.InvariantCulture);
        return new DateTimeOffset(Day.ToDateTime(time), Ontario);
    }

    /// <summary>[km east, km north] of the branch, to latitude and longitude.</summary>
    private static GeoPoint Point(double[] km) =>
        new(Branch.Latitude + (km[1] / 111.0), Branch.Longitude + (km[0] / (111.0 * Math.Cos(Branch.Latitude * Math.PI / 180))));

    private static readonly JsonSerializerOptions Json = new() { PropertyNameCaseInsensitive = true };

    public sealed record ScenarioFile(string About, List<Scenario> Scenarios);

    public sealed record Scenario(string Id, string Why, ScenarioJob Job, List<ScenarioTechnician> Technicians, string Expect);

    public sealed record ScenarioJob(string Work, string Licence, string Window, int Minutes, double[] At);

    public sealed record ScenarioTechnician(string Name, string Skills, string Licences, List<ScenarioVisit>? Day);

    public sealed record ScenarioVisit(string Window, int Minutes, double[] At);
}
