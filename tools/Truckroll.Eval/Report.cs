using System.Globalization;
using System.Text;

namespace Truckroll.Eval;

/// <summary>The numbers, and the markdown page they're written to.</summary>
internal static class Report
{
    public static readonly string[] Modes = ["hybrid", "vector", "keyword", "identifier"];

    public sealed record Metrics(double HitAt1, double HitAt5, double Mrr, double MedianMilliseconds);

    public static Metrics For(IReadOnlyList<CaseResult> results, string mode)
    {
        var ranks = results.Select(r => r.RankByMode[mode]).ToList();
        var times = results.Select(r => r.MillisecondsByMode[mode]).Order().ToList();
        return new Metrics(
            ranks.Count(r => r == 1) / (double)ranks.Count,
            ranks.Count(r => r <= 5) / (double)ranks.Count,
            ranks.Sum(r => r is { } rank ? 1.0 / rank : 0) / ranks.Count,
            times.Count == 0 ? 0 : times[times.Count / 2]);
    }

    /// <summary>The bars from issue #12. Returns what failed, empty when everything passed.</summary>
    public static List<string> CheckBars(IReadOnlyList<CaseResult> results)
    {
        var hybrid = For(results, "hybrid");
        var vector = For(results, "vector");
        var failures = new List<string>();
        if (hybrid.HitAt5 < 0.95)
        {
            failures.Add($"hybrid hit@5 is {hybrid.HitAt5:0.00}, below 0.95");
        }

        if (hybrid.HitAt1 < vector.HitAt1)
        {
            failures.Add($"hybrid hit@1 ({hybrid.HitAt1:0.00}) is below vector alone ({vector.HitAt1:0.00})");
        }

        return failures;
    }

    public static string Markdown(IReadOnlyList<CaseResult> results, DateTimeOffset ranAt, string target)
    {
        var page = new StringBuilder();
        void Line(string text = "") => page.Append(text).Append('\n');

        Line("# Retrieval eval results");
        Line();
        Line("<!-- Generated by `dotnet run --project tools/Truckroll.Eval -- --write`. Don't edit by hand: change evals/retrieval.json or the code, and run it again. -->");
        Line();
        Line(Invariant($"Ran {ranAt:yyyy-MM-dd HH:mm} UTC against {target}, as the owner (who can see everything), with {results.Count} questions from [retrieval.json](retrieval.json). A question scores at rank *n* when its first acceptable passage is the *n*th result."));
        Line();

        var failures = CheckBars(results);
        Line(failures.Count == 0
            ? "**Bars met:** hybrid hit@5 ≥ 0.95, and hybrid hit@1 ≥ vector alone."
            : $"**Bars missed:** {string.Join("; ", failures)}.");
        Line();

        Line("## By mode");
        Line();
        Line("| Mode | hit@1 | hit@5 | MRR | Median latency |");
        Line("| ---- | ----: | ----: | --: | -------------: |");
        foreach (var mode in Modes)
        {
            var m = For(results, mode);
            Line(Invariant($"| {mode} | {m.HitAt1:0.00} | {m.HitAt5:0.00} | {m.Mrr:0.00} | {m.MedianMilliseconds:0} ms |"));
        }

        Line();
        // The identifier ranking only answers questions that contain an identifier, so judge it on those.
        var withIdentifiers = results.Where(r => r.Case.Category == "identifier").ToList();
        if (withIdentifiers.Count > 0)
        {
            var own = For(withIdentifiers, "identifier");
            Line(Invariant($"The identifier ranking only answers questions that contain an identifier, so its overall numbers are low by design. On the {withIdentifiers.Count} identifier questions alone it scores hit@1 {own.HitAt1:0.00} and hit@5 {own.HitAt5:0.00}."));
        }
        Line();

        Line("## Hybrid by category");
        Line();
        Line("| Category | Questions | hit@1 | hit@5 | MRR |");
        Line("| -------- | --------: | ----: | ----: | --: |");
        foreach (var group in results.GroupBy(r => r.Case.Category))
        {
            var m = For(group.ToList(), "hybrid");
            Line(Invariant($"| {group.Key} | {group.Count()} | {m.HitAt1:0.00} | {m.HitAt5:0.00} | {m.Mrr:0.00} |"));
        }

        Line();
        Line("## Every question");
        Line();
        Line("Rank of the first acceptable passage in each mode; a dash means it wasn't in the top 10.");
        Line();
        Line("| Question | Category | Hybrid | Vector | Keyword | Identifier |");
        Line("| -------- | -------- | -----: | -----: | ------: | ---------: |");
        foreach (var result in results)
        {
            var ranks = Modes.Select(mode => result.RankByMode[mode]?.ToString(CultureInfo.InvariantCulture) ?? "–");
            Line($"| {result.Question.Replace("|", "\\|", StringComparison.Ordinal)} | {result.Case.Category} | {string.Join(" | ", ranks)} |");
        }

        return page.ToString();
    }

    private static string Invariant(FormattableString text) => text.ToString(CultureInfo.InvariantCulture);
}
