<#
.SYNOPSIS
    The quality gate. Everything here must pass before a PR merges.

.DESCRIPTION
    GitHub Actions is locked on this account, so this script is the CI run, and every PR says
    so. The steps, in order:

      1. dotnet format   C# style and analyzers match .editorconfig (no style debates in review);
                         EF-generated migrations are excluded
      2. dotnet build    Release build, warnings are errors (Directory.Build.props)
      3. dotnet test     xUnit against real MySQL and Redis in Testcontainers; no real models
      4. eslint          Next.js and TypeScript lint rules
      5. tsc             Generate Next.js route types, then type check the web app
      6. next build      The production bundle still builds
      7. app eslint      The technician app (mobile/): Expo's lint rules
      8. app tsc         Type check the app
      9. app tests       Vitest: the offline queue, the sync engine and the API client
     10. app export      The app's web bundle still builds (every route compiles)
     11. playwright      (-EndToEnd only) the demo path as each role, in a real browser, against
                         the running stack with the real model

    Step 11 is a run of its own: it needs the stack up (Aspire, `next dev`, Ollama), and step 6
    refuses to build while `next dev` runs. So a full check is `ci.ps1`, then start the stack and
    run `ci.ps1 -EndToEnd`. It resets the demo data first.

    The README's "Quality gate" section lists the same steps; keep the two in step.

.PARAMETER Dotnet
    Run only the .NET half (steps 1 to 3).

.PARAMETER Web
    Run only the web half (steps 4 to 6).

.PARAMETER Mobile
    Run only the technician app's steps (7 to 10).

.PARAMETER EndToEnd
    Run only the Playwright end-to-end tests (step 11) against the running stack. Set
    TRUCKROLL_URL to test somewhere other than http://localhost:3000.

.EXAMPLE
    ./scripts/ci.ps1
    ./scripts/ci.ps1 -Web
    ./scripts/ci.ps1 -Mobile
    ./scripts/ci.ps1 -EndToEnd
#>
[CmdletBinding()]
param(
    [switch] $Dotnet,
    [switch] $Web,
    [switch] $Mobile,
    [switch] $EndToEnd
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$runAll = -not ($Dotnet -or $Web -or $Mobile -or $EndToEnd)
$runDotnet = $Dotnet -or $runAll
$runWeb = $Web -or $runAll
$runMobile = $Mobile -or $runAll

function Invoke-Step([string] $Name, [scriptblock] $Command) {
    Write-Host "`n==> $Name" -ForegroundColor Cyan
    $started = Get-Date
    & $Command
    if ($LASTEXITCODE -ne 0) {
        Write-Host "FAILED: $Name" -ForegroundColor Red
        exit $LASTEXITCODE
    }
    Write-Host ("    ok ({0:n0}s)" -f ((Get-Date) - $started).TotalSeconds) -ForegroundColor Green
}

Push-Location $root
try {
    if ($runDotnet) {
        Invoke-Step 'dotnet format' { dotnet format Truckroll.slnx --verify-no-changes --verbosity quiet --exclude src/Truckroll.Data/Migrations }
        Invoke-Step 'dotnet build' { dotnet build Truckroll.slnx --configuration Release --nologo --verbosity quiet }
        Invoke-Step 'dotnet test' { dotnet test --solution Truckroll.slnx --configuration Release --no-build }
    }

    if ($runWeb) {
        Push-Location web
        try {
            # `next build` and a running `next dev` share .next/ and both use a lot of memory.
            # On a machine near its limit, running both has crashed other programs, so refuse.
            $devServer = Get-CimInstance Win32_Process -Filter "Name = 'node.exe'" |
                Where-Object { $_.CommandLine -match 'next(\.js)?["'']?\s+dev' -and $_.CommandLine -match [regex]::Escape((Get-Location).Path) }
            if ($devServer) {
                Write-Host 'A next dev server for this app is running. Stop it before the web build.' -ForegroundColor Yellow
                exit 1
            }

            Invoke-Step 'eslint' { npm run lint --silent }
            # Route and layout types are generated by Next.js; on a fresh clone they don't exist yet.
            Invoke-Step 'tsc' { npx next typegen; if ($LASTEXITCODE -eq 0) { npx tsc --noEmit } }
            Invoke-Step 'next build' { npm run build --silent }
        }
        finally { Pop-Location }
    }

    if ($runMobile) {
        Push-Location mobile
        try {
            Invoke-Step 'app eslint' { npm run lint --silent }
            Invoke-Step 'app tsc' { npm run typecheck --silent }
            Invoke-Step 'app tests' { npm test --silent }
            Invoke-Step 'app export' { npx expo export --platform web --output-dir dist }
        }
        finally { Pop-Location }
    }

    if ($EndToEnd) {
        Push-Location web
        try {
            Invoke-Step 'playwright' { npm run e2e --silent }
        }
        finally { Pop-Location }
    }

    Write-Host "`nQuality gate passed." -ForegroundColor Green
}
finally { Pop-Location }
